import { readdir, readFile } from "node:fs/promises";
import path from "node:path";
import yaml from "js-yaml";

const dataDir = path.join(process.cwd(), "data");

async function loadYaml<T>(file: string): Promise<T> {
  const raw = await readFile(path.join(dataDir, file), "utf8");
  return yaml.load(raw) as T;
}

async function loadJson<T>(file: string): Promise<T> {
  const raw = await readFile(file, "utf8");
  return JSON.parse(raw) as T;
}

export type SponsorFootnote = {
  /** The label used in the Markdown, as in `[^label]`. */
  label: string;
  /** Its number on the page, in order of first reference. */
  number: number;
  /** The footnote's Markdown text. */
  text: string;
};

export type SponsorPitch = {
  title: string;
  intro: string;
  sections: { id: string; heading: string; body: string }[];
  footnotes: SponsorFootnote[];
};

const footnoteDefinition = /^\[\^([^\]\s]+)\]:[ \t]*(.+)$/gm;
const footnoteReference = /\[\^([^\]\s]+)\](?!:)/g;

/**
 * The sponsor pitch is hand-written Markdown in `data/Sponsor.md`: a `#` title,
 * an intro paragraph, then one `##` heading per section. It is split here so
 * the page can lay each section out itself and give its heading an `id`.
 *
 * Footnotes are written the usual Markdown way (`[^label]` in the text, and a
 * `[^label]: …` line anywhere in the file). Because each section is rendered
 * separately, the Markdown renderer would put them at the end of whichever
 * section defines them; instead they are collected here, numbered across the
 * whole page, and each reference replaced by a link the page can render, so
 * the page can list them all at the bottom.
 */
export async function getSponsorPitch(): Promise<SponsorPitch> {
  const source = await readFile(path.join(dataDir, "Sponsor.md"), "utf8");

  const definitions = new Map<string, string>();
  for (const [, label, text] of source.matchAll(footnoteDefinition)) {
    definitions.set(label, text.trim());
  }
  const numbers = new Map<string, number>();
  const raw = source.replace(footnoteDefinition, "").replace(footnoteReference, (match, label: string) => {
    if (!definitions.has(label)) return match;
    if (!numbers.has(label)) numbers.set(label, numbers.size + 1);
    const n = numbers.get(label);
    return `<sup class="footnote-ref"><a href="#footnote-${label}" aria-label="Footnote ${n}">${n}</a></sup>`;
  });

  const [head, ...rest] = raw.split(/^## /m);
  const titleMatch = head.match(/^# (.+)$/m);
  return {
    title: titleMatch ? titleMatch[1].trim() : "Project Priorities",
    intro: head.replace(/^# .+$/m, "").trim(),
    sections: rest.map((chunk) => {
      const newline = chunk.indexOf("\n");
      const heading = (newline === -1 ? chunk : chunk.slice(0, newline)).trim();
      return {
        id: heading
          .toLowerCase()
          .replace(/[^a-z0-9]+/g, "-")
          .replace(/^-|-$/g, ""),
        heading,
        body: newline === -1 ? "" : chunk.slice(newline + 1).trim(),
      };
    }),
    footnotes: [...numbers].map(([label, number]) => ({ label, number, text: definitions.get(label)! })),
  };
}

